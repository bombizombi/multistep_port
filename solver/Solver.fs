// Level 1 — parametric greedy policy

type Theta =
    { HutAtMax: bool // build hut whenever kittens = maxKittens
      FieldTarget: int // stop building fields at this count
      JobWood: float // woodcutter fraction of workforce
      JobFarmer: float // farmer fraction (rest: scholar when science unlocked, miner when mining)
      JobHunter: float // hunter fraction — the only gold/furs source
      JobScholar: float // scholar fraction — science is the temple bottleneck
      ScholarFrom: int // kittens needed before assigning scholars
      HuntWhen: float // hunt when manpower >= frac of cap
      CraftSlabAt: float // craft slabs when minerals >= x * 250
      CraftPlateAt: float
      CraftManuscriptAt: float
      CraftWoodAt: float // craft wood when catnip >= x * 100
      BuildMineAt: int // kittens before mines
      BuildAmphitheatreAt: int
      BuildLibraryAt: int
      BuildWorkshopAt: int
      BuildTradepostAt: int
      ResearchFirst: string list } // fixed research order prefix

let defaultTheta : Theta =
    { HutAtMax = true
      FieldTarget = 20
      JobWood = 0.25
      JobFarmer = 0.45
      JobHunter = 0.1
      JobScholar = 0.35
      ScholarFrom = 2
      HuntWhen = 0.9
      CraftSlabAt = 1.2
      CraftPlateAt = 1.2
      CraftManuscriptAt = 1.2
      CraftWoodAt = 1.1
      BuildMineAt = 8
      BuildAmphitheatreAt = 12
      BuildLibraryAt = 10
      BuildWorkshopAt = 14
      BuildTradepostAt = 18
      ResearchFirst = [ "agriculture"; "mining"; "archery"; "animal"; "construction"; "engineering"; "writing"; "currency"; "philosophy" ] }

let huntAll (s: State) : State =
    // orig huntAll: hunting sends the hunter job's kittens; loot rolls in huntFraction
    let hctx : Game.Village.HuntContext =
        { GetEffect = Game.Effects.getEffect s.Cache
          Rand = s.Rand
          Zebras = getRes s.Pool "zebras"
          IronWill = s.IronWill
          GoldOreResearched = (match s.Spool.Techs |> Map.tryFind "goldOre" with Some t -> t.Researched | None -> false)
          AlicornmancyResearched = (match s.Ppool.Perks |> Map.tryFind "alicornmancy" with Some p -> p.Researched | None -> false)
          UnicornPastureVal = (Game.Buildings.get s.Bpool "unicornPasture" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0)
          LeaderManagerBonus = 0.0 }
    { s with Pool = Game.Village.huntAll hctx s.Pool }

// job assignment to match theta ratios
let applyJobs (theta: Theta) (s: State) : State =
    let kittens = s.Vpool.Kittens.Length
    if kittens = 0 then s
    else
        // job priority: scholars first (science is the temple bottleneck),
        // farmers cover a fraction of demand, gathering covers the rest
        let nScholar =
            if kittens >= theta.ScholarFrom then
                int (System.Math.Floor(float kittens * theta.JobScholar))
            else 0
        let rest = kittens - nScholar
        let hunterUnlocked = s.Vpool.JobUnlocked.Contains "hunter"
        let nHunter = if hunterUnlocked && rest >= 2 then max 1 (int (System.Math.Floor(float rest * theta.JobHunter))) else 0
        let nFarmer = min (rest - nHunter) (int (System.Math.Ceiling(float rest * theta.JobFarmer)))
        let nWood = max 0 (rest - nFarmer - nHunter)
        let targets = [ "woodcutter", nWood; "farmer", nFarmer; "hunter", nHunter; "scholar", max 0 nScholar ]
        // pass 1: unassign everywhere first (frees kittens for pass 2)
        let s1 =
            targets
            |> List.fold (fun acc (job, target) ->
                let current = acc.Vpool.JobValues |> Map.tryFind job |> Option.defaultValue 0
                if target < current then unassignJob job (current - target) acc else acc) s
        // pass 2: assign toward targets
        let s2 =
            targets
            |> List.fold (fun acc (job, target) ->
                let current = acc.Vpool.JobValues |> Map.tryFind job |> Option.defaultValue 0
                if target > current then assignJob job (target - current) acc else acc) s1
        s2

// one policy decision pass (cheap, every 10 ticks)
let applyPolicy (theta: Theta) (s: State) : State * PlanAction list =
    let acts = System.Collections.Generic.List<PlanAction>()
    let t = s.Ticks
    let log (action: string) (args: string list) = acts.Add({ Tick = t; Action = action; Args = args })

    let policyBuild (sCur: State) (name: string) : State =
        match Game.Buildings.get sCur.Bpool name with
        | Some b when b.Unlocked ->
            let prices = Game.Buildings.getAllPrices sCur.Cache (pctx sCur) b
            if Game.Resources.hasRes sCur.Pool (prices |> List.map (fun p -> (p.Resource, p.Val))) 0.0 then
                let s1 = buyBuilding name sCur
                if s1.Bpool.ByName.[name].Val > sCur.Bpool.ByName.[name].Val then
                    log "buy" [ name ]
                    s1
                else sCur
            else sCur
        | _ -> sCur

    let sH2 (sCur: State) : State = sCur

    let craftOne (sCur: State) (name: string) : State =
        match sCur.Wpool.Crafts |> Map.tryFind name with
        | Some c when c.Unlocked ->
            let s1 = craft name 1.0 sCur
            if s1.Wpool.Crafts.[name].Value > c.Value then log "craft" [ name; "1" ]
            s1
        | _ -> sCur

    let s1 =
        s
        // research in fixed order prefix (philosophy is the temple gate)
        |> (fun s0 ->
            // research what we can afford: unaffordable ResearchFirst entries
            // fall through to the cheapest affordable unlocked tech (real play
            // keeps the science flowing instead of idling at cap)
            let candidates =
                theta.ResearchFirst
                |> List.filter (fun n ->
                    match s0.Spool.Techs |> Map.tryFind n with
                    | Some t0 -> t0.Unlocked && not t0.Researched
                    | None -> false)
                |> fun rf ->
                    let fb =
                        s0.Spool.TechOrder
                        |> List.filter (fun n ->
                            match s0.Spool.Techs |> Map.tryFind n with
                            | Some t0 -> t0.Unlocked && not t0.Researched && t0.Def.Prices |> List.exists (fun p0 -> p0.Resource = "science")
                            | None -> false)
                    rf @ fb
            let next =
                candidates
                |> List.tryFind (fun n ->
                    match s0.Spool.Techs |> Map.tryFind n with
                    | Some t0 -> Game.Resources.hasRes s0.Pool (t0.Def.Prices |> List.map (fun p0 -> (p0.Resource, p0.Val))) 0.0
                    | None -> false)
            match next with
            | Some n ->
                match Game.Managers.research s0.CalendarDay n s0.Pool s0.Spool with
                | _, spool', true ->
                    log "research" [ n ]
                    research n s0
                | _ -> s0
            | None -> s0)
        // buildings: huts (housing), science economy, then the gold/temple chain
        |> (fun s0 ->
            let kittens = s0.Vpool.Kittens.Length
            let goldOreDone = (match s0.Wpool.Upgrades |> Map.tryFind "goldOre" with Some u -> u.Researched | None -> false)
            let sA = if theta.HutAtMax then policyBuild s0 "hut" else s0
            // libraries raise scienceMax (+250 each) — keep building while the
            // cap blocks the philosophy payout (9500)
            let sciMax = Game.Effects.getEffect s0.Cache "scienceMax"
            let sB = if sciMax < 11000.0 then policyBuild sA "library" else if kittens >= theta.BuildLibraryAt then policyBuild sA "library" else sA
            let sC = if kittens >= theta.BuildAmphitheatreAt then policyBuild sB "amphitheatre" else sB
            let sD = if kittens >= theta.BuildWorkshopAt then policyBuild sC "workshop" else sC
            let sE = if kittens >= theta.BuildTradepostAt then policyBuild sD "tradepost" else sD
            let sF = if kittens >= theta.BuildMineAt then policyBuild sE "mine" else sE
            let smelters = (Game.Buildings.get sF.Bpool "smelter" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0)
            // smelters are the gold engine once goldOre is researched
            let sG =
                if goldOreDone && smelters < 10 then policyBuild sF "smelter" else sF
            let fields = (Game.Buildings.get sG.Bpool "field" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0)
            let sH = if fields < theta.FieldTarget then policyBuild sG "field" else sH2 sG
            sH)
        // goldOre upgrade gates the whole gold chain
        |> (fun s0 ->
            match s0.Wpool.Upgrades |> Map.tryFind "goldOre" with
            | Some u when u.Unlocked && not u.Researched ->
                let s1 = buyUpgrade "goldOre" s0
                if (match s1.Wpool.Upgrades |> Map.tryFind "goldOre" with Some u -> u.Researched | None -> false) then
                    log "upgrade" [ "goldOre" ]
                    s1
                else s0
            | _ -> s0)
        // jobs
        |> applyJobs theta
        // hunts for gold/furs
        |> (fun s0 ->
            let manpower = getRes s0.Pool "manpower"
            let manpowerMax = getResMax s0.Pool "manpower"
            let hunters = s0.Vpool.JobValues |> Map.tryFind "hunter" |> Option.defaultValue 0
            if manpowerMax > 0.0 && manpower >= manpowerMax * theta.HuntWhen && hunters > 0 then
                log "huntall" []
                huntAll s0
            else s0)
    // gather: at fresh start catnip only comes from clicking; batch like a player
    let s2 =
        let catnip = getRes s1.Pool "catnip"
        let kittens = s1.Vpool.Kittens.Length
        // food buffer below ~30 ticks of demand -> click-gather (a player does this constantly early)
        if catnip < max 60.0 (0.85 * float kittens * 40.0) then
            let n = 60
            let pool' = fst (Game.Resources.addResEvent s1.CalendarDay "catnip" (float n) s1.Pool)
            acts.Add({ Tick = t; Action = "gather"; Args = [ string n ] })
            { s1 with Pool = pool' }
        else s1

    // crafts when stockpiled
    let s3 =
        s2
        |> (fun s0 ->
            let minerals = getRes s0.Pool "minerals"
            let sA =
                // slabs toward the 25 needed (keep a 250-minerals buffer for building)
                let slabs = getRes s0.Pool "slab"
                if slabs < 25.0 && minerals >= 250.0 * theta.CraftSlabAt then craftOne s0 "slab" else s0
            let iron = getRes sA.Pool "iron"
            let plates = getRes sA.Pool "plate"
            let sB =
                if plates < 15.0 && iron >= 125.0 * theta.CraftPlateAt then craftOne sA "plate" else sA
            let culture = getRes sB.Pool "culture"
            let furs = getRes sB.Pool "furs"
            let manuscripts = getRes sB.Pool "manuscript"
            let sC =
                if manuscripts < 10.0 && culture >= 400.0 && furs >= 175.0 then craftOne sB "parchment" else sB
            let sC2 =
                if manuscripts < 10.0 && getRes sC.Pool "parchment" >= 25.0 && culture >= 400.0 then craftOne sC "manuscript" else sC
            sC2
            let catnip = getRes sC.Pool "catnip"
            let wood = getRes sC.Pool "wood"
            // craft toward the next hut price (ratio 2.5) plus a buffer
            let hutVal = (Game.Buildings.get sC.Bpool "hut" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0)
            let hutPrice = 5.0 * 2.5 ** float hutVal
            let sD = if catnip >= 100.0 * theta.CraftWoodAt && wood < hutPrice + 40.0 then craftOne sC "wood" else sC
            sD)

    s3, List.ofSeq acts

type Goal =
    | Temple
    | Tech of string // researched
    | Building of string * int // built val

let goalReached (goal: Goal) (s: State) : bool =
    match goal with
    | Temple -> (Game.Buildings.get s.Bpool "temple" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0) >= 1
    | Tech n -> (match s.Spool.Techs |> Map.tryFind n with Some t0 -> t0.Researched | None -> false)
    | Building (n, v) -> (Game.Buildings.get s.Bpool n |> Option.map (fun b -> b.Val) |> Option.defaultValue 0) >= v

let rec runPolicyTo (goal: Goal) (theta: Theta) (seed: int64) (maxTicks: int) (s: State) : int * PlanAction list * State =
    // returns (ticks to goal OR -1 timeout, plan, final state)
    let plan = System.Collections.Generic.List<PlanAction>()
    let mutable cur = s
    let mutable done0 = false
    let mutable result = -1
    while not done0 && cur.Ticks < maxTicks do
        // policy pass every 10 ticks (2 game-seconds)
        if cur.Ticks % 10 = 0 then
            let s', acts = applyPolicy theta cur
            cur <- s'
            for a in acts do plan.Add(a)
        if goalReached goal cur then
            result <- cur.Ticks
            done0 <- true
        else cur <- tick cur
    result, List.ofSeq plan, cur

