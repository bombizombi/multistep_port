// Level 2: beam search over decision states (wait-collapsing)

type Node =
    { State: State
      Plan: PlanAction list
      Elapsed: int }

let resMaxOf (pool: Game.Types.ResPool) (name: string) : float = getResMax pool name

/// candidate next actions from the L0 vocabulary present in the current state
let candidateActions (s: State) : (string * string list) list =
    let out = System.Collections.Generic.List<string * string list>()
    // buildings worth considering (unlocked, not at target)
    for n in [ "hut"; "field"; "library"; "amphitheatre"; "workshop"; "mine"; "tradepost"; "smelter"; "temple" ] do
        match Game.Buildings.get s.Bpool n with
        | Some b when b.Unlocked -> out.Add(("buy", [ n ]))
        | _ -> ()
    // next unresearched tech
    let nextTech =
        s.Spool.TechOrder
        |> List.tryFind (fun n ->
            match s.Spool.Techs |> Map.tryFind n with
            | Some t0 -> t0.Unlocked && not t0.Researched && t0.Def.Prices |> List.exists (fun p -> p.Resource = "science")
            | None -> false)
    match nextTech with
    | Some n -> out.Add(("research", [ n ]))
    | None -> ()
    // crafts
    for c in [ "slab"; "plate"; "manuscript"; "wood" ] do
        match s.Wpool.Crafts |> Map.tryFind c with
        | Some c0 when c0.Unlocked -> out.Add(("craft", [ c; "1" ]))
        | _ -> ()
    // hunts
    let manpower = getRes s.Pool "manpower"
    if resMaxOf s.Pool "manpower" > 0.0 && manpower > 0.0 then out.Add(("huntall", []))
    List.ofSeq out

/// wait until the action is affordable (or give up after maxWait ticks), then execute
let waitForAndExecute (action: string * string list) (maxWait: int) (s0: State) : Node option =
    let (kind, args) = action
    let mutable s = s0
    let mutable waited = 0
    let affordable () =
        match kind with
        | "buy" ->
            match Game.Buildings.get s.Bpool args.[0] with
            | Some b ->
                Game.Resources.hasRes s.Pool
                    (Game.Buildings.getAllPrices s.Cache (pctx s) b |> List.map (fun p -> (p.Resource, p.Val)))
                    0.0
            | None -> false
        | "research" ->
            match s.Spool.Techs |> Map.tryFind args.[0] with
            | Some t0 ->
                Game.Resources.hasRes s.Pool (t0.Def.Prices |> List.map (fun p -> (p.Resource, p.Val))) 0.0
            | None -> false
        | "craft" ->
            match s.Wpool.Crafts |> Map.tryFind args.[0] with
            | Some c0 -> Game.Resources.hasRes s.Pool (c0.Def.Prices |> List.map (fun p -> (p.Resource, p.Val * 1.0))) 0.0
            | None -> false
        | "huntall" -> getRes s.Pool "manpower" >= 1.0
        | _ -> false
    let changed () =
        match kind with
        | "buy" ->
            let vNow = Game.Buildings.get s.Bpool args.[0] |> Option.map (fun b -> b.Val) |> Option.defaultValue 0
            let v0 = Game.Buildings.get s0.Bpool args.[0] |> Option.map (fun b -> b.Val) |> Option.defaultValue 0
            vNow > v0
        | "research" ->
            (match s.Spool.Techs |> Map.tryFind args.[0] with Some t0 -> t0.Researched | None -> false)
        | "craft" ->
            (s.Wpool.Crafts.[args.[0]].Value > s0.Wpool.Crafts.[args.[0]].Value)
        | "huntall" -> true
        | _ -> false
    while waited < maxWait && not (affordable ()) do
        s <- tick s
        waited <- waited + 1
    if waited >= maxWait && not (affordable ()) then None
    else
        // execute
        let executed =
            match kind with
            | "buy" ->
                let s1 = buyBuilding args.[0] s
                if s1.Bpool.ByName.[args.[0]].Val > s.Bpool.ByName.[args.[0]].Val then Some s1 else None
            | "research" ->
                let s1 = research args.[0] s
                if s1.Spool.Techs.[args.[0]].Researched then Some s1 else None
            | "craft" ->
                let s1 = craft args.[0] 1.0 s
                if s1.Wpool.Crafts.[args.[0]].Value > s.Wpool.Crafts.[args.[0]].Value then Some s1 else None
            | "huntall" -> Some (huntAll s)
            | _ -> None
        match executed with
        | Some s1 ->
            // let the policy run jobs in between (huts etc. matter)
            let s2, _ = applyPolicy defaultTheta s1
            Some({ State = s2; Plan = [ { Tick = s0.Ticks + waited; Action = kind; Args = args } ]; Elapsed = s0.Ticks + waited })
        | None -> None

let templeReached (s: State) : bool =
    (Game.Buildings.get s.Bpool "temple" |> Option.map (fun b -> b.Val) |> Option.defaultValue 0) >= 1

let level2 (seed: int64) (beamWidth: int) (maxNodes: int) (maxWait: int) (maxElapsed: int) : Node option =
    let start = initSeeded seed
    let beam = System.Collections.Generic.List<Node>([ { State = start; Plan = []; Elapsed = 0 } ])
    let mutable expansions = 0
    let mutable result : Node option = None
    while beam.Count > 0 && expansions < maxNodes && result.IsNone do
        let next = System.Collections.Generic.List<Node>()
        for node in beam do
            if templeReached node.State then
                result <- Some node
            elif node.Elapsed < maxElapsed then
                for action in candidateActions node.State do
                    expansions <- expansions + 1
                    if expansions > maxNodes then ()
                    else
                        match waitForAndExecute action maxWait node.State with
                        | Some child ->
                            next.Add({ child with Plan = node.Plan @ child.Plan; Elapsed = child.Elapsed })
                        | None -> ()
        if result.IsNone then
            // rank by L1-policy rollout (cheap estimate: run policy to completion, cap ticks)
            let ranked =
                next
                |> Seq.toList
                |> List.map (fun node ->
                    let ticks, _, _ = runPolicyTo Temple defaultTheta seed (node.Elapsed + 4000) node.State
                    let estimate =
                        if ticks >= 0 then float ticks
                        else float (node.Elapsed + 4000) * 1.5
                    node, estimate)
                |> List.sortBy snd
            beam.Clear()
            for node, _ in ranked |> List.truncate beamWidth do
                beam.Add(node)
            // reached during this round?
            match beam |> Seq.tryFind (fun n -> templeReached n.State) with
            | Some n -> result <- Some n
            | None -> ()
    result

// ---------------------------------------------------------------------------
// Level 3: seed sweep of the winning plan + report

let sweepSeeds (goal: Goal) (theta: Theta) (seeds: int64 list) (maxTicks: int) : (int64 * int) list =
    seeds |> List.map (fun seed -> seed, (let t, _, _ = runPolicyTo goal theta seed maxTicks (initSeeded seed) in t))

