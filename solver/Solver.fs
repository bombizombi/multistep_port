// Program entry

[<EntryPoint>]
let main argv =
    let mode = if argv.Length > 0 then argv.[0] else "l1"
    let seeds = [ 1L; 2L; 3L; 4L; 5L ]
    let maxTicks = 60000 // 100 game-days*4000... generous: ~15 game years

    match mode with
    | "l1" ->
        let goal = Temple
        let theta, score = level1 goal seeds maxTicks
        printfn "L1 best: %.0f ticks (avg over %d seeds)" score seeds.Length
        printfn "theta: %A" theta
        let _, plan, _ = runPolicyTo goal theta seeds.[0] maxTicks (initSeeded seeds.[0])
        System.IO.File.WriteAllText("../oracle/scenarios/temple-solver.cat", emitCat "temple-solver" 1 plan)
        printfn "plan written (%d actions)" plan.Length
        0
    | "l2" ->
        match level2 1L 60 4000 6000 40000 with
        | Some node ->
            printfn "L2 plan: %d ticks, %d actions" node.Elapsed node.Plan.Length
            for a in node.Plan do printfn "  %d %s %s" a.Tick a.Action (String.concat " " a.Args)
            System.IO.File.WriteAllText("../oracle/scenarios/temple-solver.cat", emitCat "temple-solver" 1 node.Plan)
            0
        | None ->
            printfn "L2: no plan found within limits"
            1
    | "l3" ->
        // seed sweep of the L1-tuned policy
        let theta, _ = level1 Temple seeds maxTicks
        let wide = [ 1L..20L ] |> List.map (fun i -> i * 7919L)
        let results = sweepSeeds Temple theta wide maxTicks
        let ok = results |> List.filter (fun (_, t) -> t >= 0)
