module Solver

// Kittens solver — levels 1-3 over the verified Game library.
// Level 1: parametric greedy policy + coordinate descent (the workhorse)
// Level 2: beam search over decision states with L1-policy rollouts
// Level 3: seed sweep + report; emits the winning plan as a .cat scenario
//
// Everything runs through kittens_land.KittensState's tick/actions — the same
// verified code the browser and the oracle use. Determinism: State.Rand is the
// ported splitmix32->sfc32 stream seeded per run.

open kittens_land.KittensState

// ---------------------------------------------------------------------------
// .cat emission — solver plans must be re-runnable through the oracle drivers

type PlanAction =
    { Tick: int
      Action: string
      Args: string list }

let emitCat (name: string) (seed: int) (actions: PlanAction list) : string =
    let lines = System.Collections.Generic.List<string>()
    lines.Add(sprintf "# name: %s" name)
    lines.Add(sprintf "# seed: %d" seed)
    lines.Add("# checkpoints: " + (actions |> List.map (fun a -> a.Tick) |> List.distinct |> List.sort |> List.map string |> String.concat ", "))
    lines.Add("# generated by solver/ — fastest-path plan, oracle-verifiable")
    lines.Add("0 resop seed " + string seed)
    let mutable lastTick = 0
    for a in actions |> List.sortBy (fun x -> x.Tick) do
        if a.Tick > lastTick then
            lines.Add(sprintf "%d resop gtick %d" lastTick (a.Tick - lastTick))
            lastTick <- a.Tick
        let args = a.Args |> String.concat " "
        lines.Add(sprintf "%d %s %s" a.Tick a.Action args)
    String.concat "\n" lines

