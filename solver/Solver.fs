// Level 1 search: coordinate descent over theta

let clamp01 (v: float) : float = max 0.05 (min 0.9 v)

let jitterTheta (theta: Theta) (dim: int) (direction: int) : Theta =
    // dimensions: 0 JobWood, 1 JobFarmer, 2 ScholarFrom, 3 HuntWhen, 4 CraftSlabAt,
    // 5 CraftPlateAt, 6 CraftManuscriptAt, 7 CraftWoodAt, 8 FieldTarget, 9 BuildMineAt
    match dim with
    | 0 -> { theta with JobWood = clamp01 (theta.JobWood + 0.05 * float direction) }
    | 1 -> { theta with JobFarmer = clamp01 (theta.JobFarmer + 0.05 * float direction) }
    | 10 -> { theta with JobHunter = clamp01 (theta.JobHunter + 0.05 * float direction) }
    | 11 -> { theta with JobScholar = clamp01 (theta.JobScholar + 0.05 * float direction) }
    | 2 -> { theta with ScholarFrom = max 4 (theta.ScholarFrom + 2 * direction) }
    | 3 -> { theta with HuntWhen = clamp01 (theta.HuntWhen + 0.05 * float direction) }
    | 4 -> { theta with CraftSlabAt = max 1.0 (theta.CraftSlabAt + 0.1 * float direction) }
    | 5 -> { theta with CraftPlateAt = max 1.0 (theta.CraftPlateAt + 0.1 * float direction) }
    | 6 -> { theta with CraftManuscriptAt = max 1.0 (theta.CraftManuscriptAt + 0.1 * float direction) }
    | 7 -> { theta with CraftWoodAt = max 1.0 (theta.CraftWoodAt + 0.1 * float direction) }
    | 8 -> { theta with FieldTarget = max 4 (theta.FieldTarget + 2 * direction) }
    | 9 -> { theta with BuildMineAt = max 6 (theta.BuildMineAt + 2 * direction) }
    | _ -> theta

let fitness (goal: Goal) (seeds: int64 list) (theta: Theta) (maxTicks: int) : float =
    let results =
        seeds
        |> List.map (fun seed ->
            let ticks, _, _ = runPolicyTo goal theta seed maxTicks (initSeeded seed)
            if ticks < 0 then float maxTicks * 1.5 else float ticks)
    List.average results

let level1 (goal: Goal) (seeds: int64 list) (maxTicks: int) : Theta * float =
    let mutable best = defaultTheta
    let mutable bestScore = fitness goal seeds best maxTicks
    printfn "L1 baseline: %.0f ticks" bestScore
    let dims = 12
    let mutable step = 1
    while step >= -1 do
        let mutable dim = 0
        while dim < dims do
            let candidate = jitterTheta best dim step
            let score = fitness goal seeds candidate maxTicks
            if score < bestScore then
                best <- candidate
                bestScore <- score
                printfn "L1 improved (dim %d, step %+d): %.0f ticks" dim step score
            dim <- dim + 1
        step <- step - 1
    best, bestScore

