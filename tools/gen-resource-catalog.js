#!/usr/bin/env node
"use strict";
/**
 * gen-resource-catalog.js — generate the F# resource definition catalog
 * (kittens_land/src/Game/Game.Catalog.Resources.fs) from the orig dump
 * (oracle/fixtures/resource-catalog-orig.json, produced by
 * `node oracle/runner/orig-driver.js --dump-catalog`).
 *
 * Generated code is checked in; rerun this after re-dumping a new orig snapshot.
 * Never hand-edit Game.Catalog.Resources.fs.
 *
 * Usage: node tools/gen-resource-catalog.js
 */
const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..");
const src = JSON.parse(fs.readFileSync(path.join(REPO, "oracle", "fixtures", "resource-catalog-orig.json"), "utf8"));

const fbool = (v) => (v ? "true" : "false");
const fopt = (v) => (v === null || v === undefined ? "None" : `Some ${JSON.stringify(v)}`);

const lines = src.catalog.map((r) =>
  `      { Name = ${JSON.stringify(r.name)}; Category = ${JSON.stringify(r.type)}; Visible = ${fbool(r.visible)};` +
  ` Color = ${fopt(r.color)}; Craftable = ${fbool(r.craftable)}; CalculatePerTick = ${fbool(r.calculatePerTick)};` +
  ` Persists = ${fbool(r.persists)}; AiCanDestroy = ${fbool(r.aiCanDestroy)}; Transient = ${fbool(r.transient)};` +
  ` Tag = ${fopt(r.tag)}; IsNotRefundable = ${fbool(r.isNotRefundable)}; CalculatePerDay = ${fbool(r.calculatePerDay)};` +
  ` CalculatePerTickAndDay = ${fbool(r.calculatePerTickAndDay)}; CalculateOnYear = ${fbool(r.calculateOnYear)};` +
  ` RefundableRule = ${r.hasCustomIsRefundable ? "EnergyBalanced" : "Default"} }`
);

const out = `//------------------------------------------------------------------------------
// GENERATED by tools/gen-resource-catalog.js from
// oracle/fixtures/resource-catalog-orig.json (orig @ ${src.origCommit.slice(0, 12)}).
// resources-01 (data): the resourceData catalog, all logic-relevant flags.
// i18n titles/descriptions/flavors are intentionally omitted (UI layer, later unit).
// Never hand-edit — regenerate instead.
//------------------------------------------------------------------------------

module Game.Catalog.Resources

open Game.Types

let resourceDefs : ResourceDef list =
    [
${lines.join("\n")}
    ]
`;

const target = path.join(REPO, "kittens_land", "src", "Game", "Game.Catalog.Resources.fs");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out);
console.log(`wrote ${path.relative(REPO, target)} (${src.catalog.length} resources)`);
