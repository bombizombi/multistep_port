#!/usr/bin/env node
"use strict";
/**
 * gen-defs-catalogs.js — generate Game.Catalog.Defs.fs (buildings/techs/
 * policies/upgrades/crafts) from oracle/fixtures/defs-orig.json (produced by
 * `node oracle/runner/orig-driver.js --dump-defs`).
 *
 * Building effects: every calculateEffects in orig is val-CONSTANT (verified in
 * session 08), so the def carries the FINAL effects table; val/on scaling lives
 * in the provider (Game.Buildings.providerEffect). Stages carry their own tables.
 *
 * Generated code is checked in. Never hand-edit the F# file.
 */
const fs = require("fs");
const path = require("path");

const REPO = path.resolve(__dirname, "..");
const src = JSON.parse(fs.readFileSync(path.join(REPO, "oracle", "fixtures", "defs-orig.json"), "utf8"));

const fstr = (s) => JSON.stringify(s === null || s === undefined ? "" : s);
const foptS = (s) => (s === null || s === undefined ? "None" : `Some ${JSON.stringify(s)}`);
const foptF = (f) => (f === null || f === undefined ? "None" : `Some ${f}`);
const fbool = (b) => (b ? "true" : "false");
const fprices = (ps) =>
  ps.length === 0
    ? "[]"
    : "[" + ps.map((p) => `{ Resource = ${JSON.stringify(p.name)}; Val = ${p.val} }`).join("; ") + "]";
const funlocks = (u) =>
  u === null
    ? "None"
    : `Some({ Buildings = [${(u.buildings || []).map(fstr).join("; ")}]; Tabs = [${(u.tabs || []).map(fstr).join("; ")}]; Jobs = [${(u.jobs || []).map(fstr).join("; ")}]; Tech = [${(u.tech || []).map(fstr).join("; ")}]; Policies = [${(u.policies || []).map(fstr).join("; ")}]; Upgrades = [${(u.upgrades || []).map(fstr).join("; ")}]; Stages = [${(u.stages || []).map(fstr).join("; ")}] })`;
const fmap = (m) =>
  !m || Object.keys(m).length === 0
    ? "Map.empty"
    : "Map.ofList [" + Object.entries(m).map(([k, v]) => `${JSON.stringify(k)}, ${v}`).join("; ") + "]";

const buildingLines = src.buildings.map((b) => {
  // final effects table: calc result if present (constant), else static table
  const effects = b.calc ? (b.calc.atVal0 || {}) : (b.effectsBase || {});
  const stageLines = (b.stages || [])
    .map((s) =>
      `        { StageKey = ${foptS(s.key)}; Prices = ${fprices(s.prices)}; UnlockRatio = ${foptF(s.unlockRatio)}; Effects = ${fmap(s.effects)} }`)
    .join("\n");
  const stages =
    (b.stages || []).length === 0
      ? "[]"
      : "[\n" + stageLines + "\n      ]";
  return `      { Name = ${fstr(b.name)}; Tab = ${foptS(b.tab)}; Stage = ${b.stage || 0};
        UnlockRatio = ${foptF(b.unlockRatio)}; DefaultUnlockable = ${fbool(b.defaultUnlockable)};
        Prices = ${fprices(b.prices)}; PriceRatio = ${foptF(b.priceRatio)};
        LimitBuild = ${foptF(b.limitBuild)}; TogglableOnOff = ${fbool(b.togglableOnOff)};
        NoStackable = ${fbool(b.noStackable)}; BreaksIronWill = ${fbool(b.breaksIronWill)};
        Effects = ${fmap(effects)}; StartsUnlocked = ${fbool(b.unlocked)}; StartsUnlockable = ${fbool(b.unlockable)};
        Stages = ${stages};
        Unlocks = ${funlocks(b.unlocks)}; Upgrades = ${funlocks(b.upgrades)};
        UnlockScheme = ${b.unlockScheme ? `Some(${fstr(b.unlockScheme.name)}, ${b.unlockScheme.threshold})` : "None"} }`;
});

const techLines = src.techs.map((t) =>
  `      { Name = ${fstr(t.name)}; Prices = ${fprices(t.prices)}; Unlocks = ${funlocks(t.unlocks)} }`);
const policyLines = src.policies.map((p) =>
  `      { Name = ${fstr(p.name)}; Prices = ${fprices(p.prices)}; Unlocks = ${funlocks(p.unlocks)} }`);
const upgradeLines = src.upgrades.map((u) =>
  `      { Name = ${fstr(u.name)}; Prices = ${fprices(u.prices)}; Effects = ${fmap(u.effects)} }`);
const craftLines = src.crafts.map((c) =>
  `      { Name = ${fstr(c.name)}; Prices = ${fprices(c.prices)}; Tier = ${foptF(c.tier)}; IgnoreBonuses = ${fbool(c.ignoreBonuses)}; StartsUnlocked = ${fbool(c.unlocked)} }`);

const out = `//------------------------------------------------------------------------------
// GENERATED by tools/gen-defs-catalogs.js from oracle/fixtures/defs-orig.json
// (orig @ ${src.origCommit.slice(0, 12)}).
// buildings-01 / science-01 / science-02(data) / workshop-01 / workshop-02:
// all static definitions. calculateEffects functions in orig are val-constant
// (verified session 08) — their resolved tables are baked in as Effects; the
// val/on scaling lives in Game.Buildings.providerEffect (core.js provider port).
// i18n labels/descriptions omitted (UI layer). Never hand-edit — regenerate.
//------------------------------------------------------------------------------

module Game.Catalog.Defs

open Game.Types

let buildingDefs : BuildingDef list =
    [
${buildingLines.join("\n")}
    ]

let techDefs : TechDef list =
    [
${techLines.join("\n")}
    ]

let policyDefs : PolicyDef list =
    [
${policyLines.join("\n")}
    ]

let upgradeDefs : UpgradeDef list =
    [
${upgradeLines.join("\n")}
    ]

let craftDefs : CraftDef list =
    [
${craftLines.join("\n")}
    ]
`;

const target = path.join(REPO, "kittens_land", "src", "Game", "Game.Catalog.Defs.fs");
fs.writeFileSync(target, out);
console.log(`wrote Game.Catalog.Defs.fs (buildings ${src.buildings.length}, techs ${src.techs.length}, policies ${src.policies.length}, upgrades ${src.upgrades.length}, crafts ${src.crafts.length})`);
