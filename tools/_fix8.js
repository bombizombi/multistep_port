#!/usr/bin/env node
"use strict";
// game-17: reset flow — resetInternal blob transform + gtick pause wrapper +
// reset/applyreset moves + getResetPrestige probe
const fs = require("fs");
const p = "oracle/runner/fs-runner/Program.fs";
let lines = fs.readFileSync(p, "utf8").split("\n");
const norm = (s) => s.replace(/\r/g, "");
const findIdx = (pred, from = 0) => {
  for (let i = from; i < lines.length; i++) if (pred(norm(lines[i]))) return i;
  return -1;
};

// ---- 0. state mutables near pausedReset needs: add beside scheduledEvents ----
let i0 = findIdx((l) => l.includes("let mutable scheduledFired = 0"));
if (i0 < 0) throw new Error("schedFired");
lines.splice(i0 + 1, 0,
  "    let mutable pausedReset = false // post-_resetInternal pause (isPaused)",
  "    let mutable resetPendingFlag = false // timer.scheduleEvent(resetAutomatic)");

// ---- 1. karmaZebras save write (intv 0 → live value) ----
